const DICT: Record<DashboardLocale, Record<DashboardTranslationKey, string>> = { es, en }

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`))
}

export function translateDashboard(
  locale: DashboardLocale,
  key: DashboardTranslationKey,
  vars?: Record<string, string | number>
): string {
  return interpolate(DICT[locale]?.[key] ?? DICT.es[key] ?? key, vars)
}

export function dashboardT(locale: DashboardLocale) {
  return (key: DashboardTranslationKey, vars?: Record<string, string | number>) =>
    translateDashboard(locale, key, vars)
}

